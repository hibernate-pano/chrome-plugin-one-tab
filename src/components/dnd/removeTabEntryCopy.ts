/**
 * 单条标签的 ✕ 入口文案 —— 「删掉这一条会发生什么」。
 *
 * ── 缺陷本体（2026-10-23 审计 DS-43-16）────────────────────────────────────
 * v1.22.0 起删除是**物理清除**（无回收站、无撤销）。而「删掉会话里的**最后一条**」
 * 等于「删掉整个会话」—— 整张卡会从列表里消失。
 *
 * 「删除会话前确认」开关**打开**时这件事会弹确认框（「删除「X」？」），
 * 用户看得见；但开关**关闭**时**零确认** ⇒ 整张卡静默消失，
 * 而 ✕ 的提示只说「从会话中移除这条记录（无法恢复）」——
 * **没说整张会话卡会一起消失**。
 *
 * ⇒ 后果必须写在**按钮自己身上**：提示同时是可访问名的一部分
 * （`title` + `aria-label`）⇒ 读屏用户与视觉用户拿到同一句契约。
 *
 * ── 判据为什么不是「组里还剩几条标签」────────────────────────────────────
 * 真相是 `shouldAutoDeleteAfterTabRemoval`（`src/core/tabGroupUtils.ts`）：
 * 它只数**活跃**（非墓碑）标签 —— 墓碑是同步用的删除意图，不代表用户可见内容。
 * 用「组里一共几条」会把墓碑算进去 ⇒ 最后一页还显示着 3 条、删掉其中一条却
 * 整组消失，提示反而说错了。
 */
export interface RemoveTabEntryCopy {
  /** 悬停提示（完整句）。 */
  title: string;
  /** 可访问名的**动作部分**（调用方会再拼上标签名）。 */
  action: string;
}

/**
 * 单条 ✕ 的文案。
 *
 * @param input.removesWholeSession 删掉这一条之后，整个会话会不会一起消失。
 */
export const removeTabEntryCopy = (input: {
  removesWholeSession: boolean;
}): RemoveTabEntryCopy =>
  input.removesWholeSession
    ? {
        // 必须说清是**整个会话**会消失（不是「这条记录」）——
        // 用户看到的现象是「一张卡不见了」，提示要能对上那个现象。
        title: '删掉这条会移除整个会话（无法恢复）',
        action: '删掉这条（会移除整个会话，无法恢复）',
      }
    : {
        title: '从会话中移除这条标签页（无法恢复）',
        action: '从会话中移除（无法恢复）',
      };
