/**
 * 「锁定 / 解锁会话」的用户可见反馈（2026-10-22 审计 L-9）。
 *
 * ── 缺陷原形 ────────────────────────────────────────────────────────────
 * 锁定是一个**有语义的状态变更**，它改变的是「恢复之后这个会话还在不在」：
 *
 *   · 未锁定：恢复整个会话 ⇒ 会话被消费（从列表移除）；
 *   · 已锁定：恢复整个会话 ⇒ 会话**保留**，可以反复使用。
 *
 * 但锁定成功后，界面上**一句话都没有**。唯一的反馈是卡片头多了一颗锁图标
 * 与按钮 aria-label 变成「解锁会话」—— 而这个语义**只写在 tooltip 里**。
 *
 * ── 2026-10-25「安静的成功」：播报 ⇒ **常驻一行** ────────────────────────
 *
 * 锁定不是一次「完成」事件，而是**一条规则的披露**：它改了本产品**唯一**
 * 一条会被说反的规则（见 restoreFeedbackCopy —— 恢复即消费）。
 * 而 toast 是**会消失**的 ⇒ 4 秒之后那句话就没了 ⇒ 用户仍然要靠记忆。
 *
 * ⇒ 这句话改挂在卡片上，**常驻**：
 *   · 锁定 ⇒ 卡片上多一行小字，随时可查，不占屏幕中心；
 *   · 解锁 ⇒ 那行**消失**（那行消失本身就是反馈）⇒ **解锁完全静默**。
 *
 * 为什么解锁也不出声：解锁是**移除**保护、回到默认行为，而默认行为的后果
 * **本来就**写在恢复按钮的 tooltip 与 aria-label 上（`restoreOutcomeSentence(false)`
 * =「恢复后该会话会从列表移除，不可恢复」）⇒ 随时可查。
 * ⚠️ 2026-10-26：撤销机制下线后，这句话里的「不可恢复」是**唯一**的告知 ——
 *   「可撤销」已经不存在了（见 restoreFeedbackCopy 的说明）。
 * 危险的方向是「锁定」（用户以为消费了其实没消费），不是「解锁」。
 *
 * ── 为什么抽成纯函数 ────────────────────────────────────────────────────
 * 宽屏按钮与窄屏「更多」菜单是**两个入口**（见 TabGroup.tsx），
 * 历史 bug 正是两处各写一份判据、改一处漏一处。抽出后措辞只有一份，
 * node 单测可以直接断言。
 */

/**
 * 锁定状态下**常驻在卡片上**的说明。
 *
 * @param isLocked 当前是否已锁定。false ⇒ **null**（那行不渲染 —— 那行消失就是反馈）。
 *
 * ⚠️ 文案必须含三个要素（守卫按关键词断言，不钉整句字面量）：
 *   ① **已锁定** —— 状态是什么；
 *   ② **恢复后保留在列表** —— 锁定唯一改变的那条规则（消费语义）；
 *   ③ **不参与「清理重复标签」与拖到别的会话** —— 界面**不会**告诉你、
 *      却又真实存在的后果（README:43 承诺过「不可把标签拖到别的会话」）。
 *
 * 其余后果（不可重命名、不可逐条删除）在界面上是**按钮消失 / 禁用** ⇒ 界面自明
 * ⇒ 不必写出来（写了就是噪音）。
 */
export const lockDisclosureText = (isLocked: boolean): string | null =>
  isLocked
    ? '已锁定 · 恢复后保留在列表 · 不参与「清理重复标签」与拖到别的会话'
    : null;
