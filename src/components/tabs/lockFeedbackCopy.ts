/**
 * 「锁定 / 解锁会话」的用户可见反馈（2026-10-22 审计 L-9）。
 *
 * ── 缺陷原形 ────────────────────────────────────────────────────────────
 * 锁定是一个**有语义的状态变更**，它改变的是「恢复之后这个会话还在不在」：
 *
 *   · 未锁定：恢复整个会话 ⇒ 会话被消费（从列表移除）；
 *   · 已锁定：恢复整个会话 ⇒ 会话**保留**，可以反复使用。
 *
 * 但锁定成功后，界面上**一句话都没有**。唯一的反馈是卡片头多了一颗锁图标
 * 与按钮 aria-label 变成「解锁会话」—— 而这个语义**只写在 tooltip 里**。
 * 实测（scripts/lead-interact.mjs，锁定一步）：页面可见的 toast / 提示为**空**。
 *
 * 为什么这值得单独说：恢复时消费会话是本产品**最容易被误解的一条规则**
 * （见 restoreFeedbackCopy —— 恢复成功时必须说清「已从列表移除」）。
 * 锁定正是**唯一**能改变这条规则的开关，而它切换时不出声 ⇒
 * 用户在恢复之后才发现「这次没被消费」，已经晚了。
 *
 * ── 为什么抽成纯函数 ────────────────────────────────────────────────────
 * 宽屏按钮与窄屏「更多」菜单是**两个入口**（见 TabGroup.tsx），
 * 历史 bug 正是两处各写一份判据、改一处漏一处。抽出后措辞只有一份，
 * node 单测可以直接断言。
 */

/**
 * 锁定 / 解锁后的提示文案。
 *
 * @param isLocked 切换**之后**的状态（true = 已锁定）。
 */
export const lockToggleMessage = (isLocked: boolean): string =>
  isLocked
    ? '已锁定。该会话不会被「清理重复标签」清理，也不能重命名或逐条删除；恢复后它仍会留在列表里，可以反复使用。'
    : '已解锁。该会话恢复后会从列表中移除（需要反复使用请重新锁定）。';
