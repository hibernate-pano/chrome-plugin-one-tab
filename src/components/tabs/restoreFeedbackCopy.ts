/**
 * 「恢复」的用户可见文案 —— **按钮提示（点了之前）＋ 成功反馈（点了之后）**共用一份措辞。
 *
 * ── 为什么需要这个模块（2026-10-20 审计 A-1 / A-2）────────────────────────
 *
 * 恢复是本产品的**头号动作**，但它有两条截然不同的界面路径：
 *   · 列表页（TabGroup）：恢复整组 / 点开单标签
 *   · 搜索页（SearchResultList）：恢复整组 / 批量恢复命中标签
 *
 * 修复前**只有搜索页**有成功反馈（`showRestoreSuccess`），列表页**零反馈**：
 * 用户点「在新窗口恢复整个会话」→ 窗口开了、会话卡从列表消失、屏幕上什么都不动。
 * 「卡片怎么没了？」是用户看到卡片凭空消失时的第一反应，而**它其实是成功**。
 *
 * 同一产品两个界面两种反馈，是本仓反复修过的同一类问题（见 2026-10-19 审计 F-4：
 * 搜索页的确认框文案与列表页行为不一致）。所以这里把措辞抽成一处，
 * 两个界面引用同一个函数 —— 改一处就不会漂移成两个说法。
 *
 * ── 措辞必须说清「消费」语义 ──────────────────────────────────────────
 *
 * 未锁定会话恢复后**即从列表移除**（无回收站、不可恢复）。这是刻意的产品决定，
 * 但用户第一次遇到时并不知道。所以成功文案不能只说「恢复成功」——
 * 那会让用户以为会话还在，回头找不到时反而困惑。文案要同时说清两件事：
 *   ① 标签已经打开（发生了什么）
 *   ② 会话记录已从列表移除（为什么卡片不见了）
 *
 * 锁定会话不会被消费，文案相应不同。
 *
 * ── 后果的措辞为什么也归这里（2026-10-23 审计 WC-1）────────────────────────
 *
 * 「恢复之后这个会话还在不在」是本产品**唯一一条会被说反的规则**：
 *   · 未锁定：恢复即消费 ⇒ 会话从列表移除（但有撤销退路）；
 *   · 已锁定：恢复不消费 ⇒ 会话**仍保留**在列表里。
 *
 * 修复前这两件事**各写各的**：成功提示说对了，可按钮 tooltip **不看 isLocked**
 * —— 锁定会话的按钮也写着「会被移除」。而锁定恰恰是本产品**唯一**能让恢复后
 * 不被消费的开关（TabGroup.consumeSession 里 `if (group.isLocked) return;`），
 * 它的说明书却在劝退用户。
 *
 * ⇒ 把「后果短语」收成**一处**（restoreOutcomePhrase），成功提示与按钮提示
 * （tooltip / aria-label）都从它派生 ⇒ 两边不可能再漂成两个说法。
 */

// ─────────────────────────────────────────────────────────────────────────
// 「恢复之后这个会话还在不在」—— 唯一措辞出处
// ─────────────────────────────────────────────────────────────────────────

/**
 * 后果短语的**唯一出处**。
 *
 * 两个概念各只有一种叫法：
 *   · 已锁定 → 「仍保留在列表中」（成功提示里也是这半句）
 *   · 未锁定 → 「从列表移除」
 *
 * ⚠️ 改这里 = 改全产品对「恢复」的说法。成功提示与按钮提示都从这里派生，
 * 所以它们**不可能**各说各话。
 */
export const restoreOutcomePhrase = (isLocked: boolean): string =>
  isLocked ? '仍保留在列表中' : '从列表移除';

/**
 * 后果的**整句**（点了之前的说法）：按钮 tooltip 与 aria-label 共用同一句。
 *
 * · 已锁定 → 「恢复后该会话仍保留在列表中」
 * · 未锁定 → 「恢复后该会话会从列表移除，可撤销」
 *   （未锁定那一步的移除**有退路**：成功提示上挂着「撤销」按钮，见 useConsumeUndo）
 */
export const restoreOutcomeSentence = (isLocked: boolean): string =>
  isLocked
    ? `恢复后该会话${restoreOutcomePhrase(true)}`
    : `恢复后该会话会${restoreOutcomePhrase(false)}，可撤销`;

/**
 * 整组恢复成功的文案。
 *
 * ── `inCurrentWindow`：说「在哪个窗口打开」（2026-10-25）────────────────────
 *
 * 恢复有**两条**路径，开在**不同的窗口**：
 *   · 「在当前窗口打开整个会话」→ 标签加到**当前**窗口；
 *   · 「在新窗口恢复整个会话」→ 另开一扇窗。
 *
 * 修复前这句话**写死**成「已在新窗口打开 N 个标签页」⇒ 点「在当前窗口打开」
 * 也会这么说 —— 界面在**撒谎**（用户看到标签明明加在了眼前这个窗口，
 * 提示却说新窗口）。这不是措辞洁癖：2026-10-25 产品负责人把「在当前窗口打开」
 * 定成**主操作**（第一位 + accent + 窄屏常驻）⇒ 这条谎话出现在最高频的那条
 * 路径上。
 *
 * ⇒ 开在哪个窗口，必须由**调用方告诉**（`inCurrentWindow`），
 *   文案只负责照着说，不许自己假设。
 */
export const restoreGroupSuccessMessage = (
  tabCount: number,
  isLocked: boolean,
  inCurrentWindow = false
): string => {
  const opened = inCurrentWindow
    ? `已在当前窗口打开 ${tabCount} 个标签页`
    : `已在新窗口打开 ${tabCount} 个标签页`;
  if (isLocked) {
    // 锁定会话恢复后保留 —— 用户可以反复用同一组。
    return `${opened}。该会话已锁定，${restoreOutcomePhrase(true)}。`;
  }
  return `${opened}。该会话已${restoreOutcomePhrase(false)}（未锁定会话恢复后即消费）；需要反复使用请先锁定它。`;
};

/**
 * 点开单个标签成功的文案。
 *
 * 点开即消费（1.24.1 定案）：标签打开后，那条记录会从会话里移除。
 * 这是**不可撤销的删除**（无回收站），却是最高频的动作 ——
 * 不出声的话，用户看到「行消失了、页面开了」，无法区分「已打开」与「被删了」。
 */
export const openSingleTabSuccessMessage = (isLocked: boolean): string => {
  if (isLocked) {
    return '已打开该标签页。该会话已锁定，记录仍保留在会话中。';
  }
  return '已打开该标签页，并从会话中移除该条记录。';
};

/**
 * 批量恢复（搜索页）成功时的**真实账目**。
 *
 * ── 为什么不是一个数字 ────────────────────────────────────────────────────
 * 批量恢复里**两件事**必须分开说（2026-10-23 审计 P0-2）：
 *
 *   · **打开了几个标签页** —— 含锁定会话里的（锁定只阻止「消费」，不阻止「打开」）；
 *   · **从会话里移除了几条记录** —— **不含**锁定会话里的（锁定会话从不被消费）。
 *
 * 修复前那句话（`已恢复 N 个标签；命中的标签已从所属会话移除…`）把这两件事
 * 混成一句 ⇒ 用户以为「命中的那些都从列表里清掉了」，而锁定会话里的那几条
 * **原封不动地还在**。
 *
 * ⇒ 这里的每个数字都必须来自**同一份判据**（哪些会被消费、哪些会被保留），
 *   而不是各数各的。判据见 `@/components/search/searchBatchRestore`。
 */
export interface BatchRestoreCounts {
  /** 这次批量恢复涉及多少个标签页（全部命中）。 */
  matched: number;
  /** 实际打开了几个（当前设备打不开的不算）。 */
  opened: number;
  /** 真正从会话里移除了几条。 */
  removed: number;
  /** 因为会话被锁定而**留在会话里**的条数。 */
  keptLocked: number;
  /** 计划移除、但没移除的条数（删除失败）。 */
  failedToRemove: number;
  /** 在当前设备打不开的条数（0 或省略 = 没有）。 */
  unopenable?: number;
}

/**
 * 批量恢复（搜索页）的**确认框正文**。
 *
 * 为什么确认框也要说清「锁定的那几条不会被移除」（2026-10-23 审计 P0-2）：
 * 成功提示修好之后，确认框还在说「命中的标签会从所属会话中移除」⇒
 * 用户在**点确认之前**就已经被承诺了一件不会发生的事。
 * ⇒ 两处必须用**同一份划分**（`BatchRestoreCounts`）算出来。
 *
 * @param counts       这次**将要**发生的账目（判据层算出的 prospective 数字）。
 * @param sessionCount 这些命中分布在几个会话里。
 */
export const restoreAllSearchConfirmMessage = (
  counts: BatchRestoreCounts,
  sessionCount: number
): string => {
  const parts: string[] = [
    `将在新窗口打开 ${sessionCount} 个会话中的 ${counts.matched} 个标签页；`,
  ];
  if (counts.keptLocked > 0) {
    parts.push(`其中 ${counts.removed} 个会从所属会话中移除，会话内其余标签页保留；`);
    parts.push(`另有 ${counts.keptLocked} 个在已锁定的会话里，仍保留在会话中。`);
  } else {
    parts.push('命中的标签页会从所属会话中移除，会话内其余标签页保留。');
  }
  parts.push('（某会话若因此被清空，会一并从列表消失；删除不可恢复。）确认继续吗？');
  return parts.join('');
};

/**
 * 批量恢复（搜索页）成功的文案 —— 与 SearchResultList 里已有的那段同口径。
 *
 * ── 为什么每一句都带**数字** ───────────────────────────────────────────────
 * 「命中的标签页已从所属会话移除」这种**无数量的说法**本身就是谎报的一半：
 * 命中的里面有一部分在锁定会话里（没被移除），说「命中的」就是把它们算进去了。
 * ⇒ 每一句都带数字，且数字**互相加得起来**（移除的 + 留下的 = 命中的）。
 *
 * 三笔账各说各的：
 *   · 打开了几个（`opened`）—— 含锁定会话里的；
 *   · 从会话里移除了几个（`removed`）—— 不含锁定会话里的；
 *   · 还剩几个在会话里（`keptLocked`）、打不开的（`unopenable`）、
 *     没移除掉的（`failedToRemove`）。
 */
export const restoreAllSearchSuccessMessage = (counts: BatchRestoreCounts): string => {
  const parts: string[] = [`已恢复 ${counts.opened} 个标签页`];

  // ① 移除的那部分。
  if (counts.removed > 0) {
    parts.push(
      `已从所属会话移除 ${counts.removed} 个标签页（会话内其余标签页保留）`
    );
  } else {
    // 一条都没移除（全都锁着 / 全都失败）—— 说清「没移除」，别让用户以为动了。
    parts.push('没有任何一条被从会话中移除');
  }

  // ② 锁定会话里留下的那几条（**用户最需要知道的那几条**）。
  if (counts.keptLocked > 0) {
    parts.push(
      `另有 ${counts.keptLocked} 个在已锁定的会话里，仍保留在会话中`
    );
  }

  // ③ 当前设备打不开的。
  if (counts.unopenable && counts.unopenable > 0) {
    parts.push(
      `另有 ${counts.unopenable} 个在当前设备无法打开` +
        '（本地文件、临时链接或浏览器内部页面）'
    );
  }

  // ④ 没移除掉的（删除失败）——不许藏。
  if (counts.failedToRemove > 0) {
    parts.push(`另有 ${counts.failedToRemove} 条未能从会话中移除`);
  }

  return `${parts.join('；')}。`;
};
