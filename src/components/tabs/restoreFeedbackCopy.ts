/**
 * 「恢复」的用户可见文案 —— **按钮提示（点了之前）＋ 成功反馈（点了之后）**共用一份措辞。
 *
 * ── 为什么需要这个模块（2026-10-20 审计 A-1 / A-2）────────────────────────
 *
 * 恢复是本产品的**头号动作**，但它有两条截然不同的界面路径：
 *   · 列表页（TabGroup）：恢复整组 / 点开单标签
 *   · 搜索页（SearchResultList）：恢复整组 / 批量恢复命中标签
 *
 * 修复前**只有搜索页**有成功反馈（`showRestoreSuccess`），列表页**零反馈**：
 * 用户点「在新窗口恢复整个会话」→ 窗口开了、会话卡从列表消失、屏幕上什么都不动。
 * 「卡片怎么没了？」是用户看到卡片凭空消失时的第一反应，而**它其实是成功**。
 *
 * 同一产品两个界面两种反馈，是本仓反复修过的同一类问题（见 2026-10-19 审计 F-4：
 * 搜索页的确认框文案与列表页行为不一致）。所以这里把措辞抽成一处，
 * 两个界面引用同一个函数 —— 改一处就不会漂移成两个说法。
 *
 * ── 措辞必须说清「消费」语义 ──────────────────────────────────────────
 *
 * 未锁定会话恢复后**即从列表移除**（无回收站、不可恢复）。这是刻意的产品决定，
 * 但用户第一次遇到时并不知道。所以成功文案不能只说「恢复成功」——
 * 那会让用户以为会话还在，回头找不到时反而困惑。文案要同时说清两件事：
 *   ① 标签已经打开（发生了什么）
 *   ② 会话记录已从列表移除（为什么卡片不见了）
 *
 * 锁定会话不会被消费，文案相应不同。
 *
 * ── 后果的措辞为什么也归这里（2026-10-23 审计 WC-1）────────────────────────
 *
 * 「恢复之后这个会话还在不在」是本产品**唯一一条会被说反的规则**：
 *   · 未锁定：恢复即消费 ⇒ 会话从列表移除（但有撤销退路）；
 *   · 已锁定：恢复不消费 ⇒ 会话**仍保留**在列表里。
 *
 * 修复前这两件事**各写各的**：成功提示说对了，可按钮 tooltip **不看 isLocked**
 * —— 锁定会话的按钮也写着「会被移除」。而锁定恰恰是本产品**唯一**能让恢复后
 * 不被消费的开关（TabGroup.consumeSession 里 `if (group.isLocked) return;`），
 * 它的说明书却在劝退用户。
 *
 * ⇒ 把「后果短语」收成**一处**（restoreOutcomePhrase），成功提示与按钮提示
 * （tooltip / aria-label）都从它派生 ⇒ 两边不可能再漂成两个说法。
 */

// ─────────────────────────────────────────────────────────────────────────
// 「恢复之后这个会话还在不在」—— 唯一措辞出处
// ─────────────────────────────────────────────────────────────────────────

/**
 * 后果短语的**唯一出处**。
 *
 * 两个概念各只有一种叫法：
 *   · 已锁定 → 「仍保留在列表中」（成功提示里也是这半句）
 *   · 未锁定 → 「从列表移除」
 *
 * ⚠️ 改这里 = 改全产品对「恢复」的说法。成功提示与按钮提示都从这里派生，
 * 所以它们**不可能**各说各话。
 */
export const restoreOutcomePhrase = (isLocked: boolean): string =>
  isLocked ? '仍保留在列表中' : '从列表移除';

/**
 * 后果的**整句**（点了之前的说法）：按钮 tooltip 与 aria-label 共用同一句。
 *
 * · 已锁定 → 「恢复后该会话仍保留在列表中」
 * · 未锁定 → 「恢复后该会话会从列表移除，可撤销」
 *   （未锁定那一步的移除**有退路**：成功提示上挂着「撤销」按钮，见 useConsumeUndo）
 */
export const restoreOutcomeSentence = (isLocked: boolean): string =>
  isLocked
    ? `恢复后该会话${restoreOutcomePhrase(true)}`
    : `恢复后该会话会${restoreOutcomePhrase(false)}，可撤销`;

/** 整组恢复成功的文案。 */
export const restoreGroupSuccessMessage = (
  tabCount: number,
  isLocked: boolean
): string => {
  const opened = `已在新窗口打开 ${tabCount} 个标签页`;
  if (isLocked) {
    // 锁定会话恢复后保留 —— 用户可以反复用同一组。
    return `${opened}。该会话已锁定，${restoreOutcomePhrase(true)}。`;
  }
  return `${opened}。该会话已${restoreOutcomePhrase(false)}（未锁定会话恢复后即消费）；需要反复使用请先锁定它。`;
};

/**
 * 点开单个标签成功的文案。
 *
 * 点开即消费（1.24.1 定案）：标签打开后，那条记录会从会话里移除。
 * 这是**不可撤销的删除**（无回收站），却是最高频的动作 ——
 * 不出声的话，用户看到「行消失了、页面开了」，无法区分「已打开」与「被删了」。
 */
export const openSingleTabSuccessMessage = (isLocked: boolean): string => {
  if (isLocked) {
    return '已打开该标签页。该会话已锁定，记录仍保留在会话中。';
  }
  return '已打开该标签页，并从会话中移除该条记录。';
};

/**
 * 批量恢复（搜索页）成功的文案 —— 复用的也是「命中的标签被移除、会话保留」语义。
 * 与 SearchResultList 里已有的那段保持同一口径。
 */
export const restoreAllSearchSuccessMessage = (tabCount: number): string =>
  `已恢复 ${tabCount} 个标签；命中的标签已从所属会话移除，会话内其余标签保留。`;
