/**
 * 「拖走最后一条标签」的用户可见文案（2026-10-23 审计 DS-43-11）。
 *
 * ── 缺陷本体 ─────────────────────────────────────────────────────────────
 * 「拖走会话里的最后一条标签」= 搬空这个会话 = **整张会话卡从列表里消失**。
 * 这是产品钦定的交互（`tests/dragLastTabRefused.test.ts` 钉住「直接生效，不多问」，
 * 2026-10-19 明确回退过 round 29 那道拦截）—— 交互本身**不动**。
 *
 * 但搬完之后：
 *   · 屏幕上那张卡**静默消失**（没有任何提示）；
 *   · 拖拽过程中**零文案**（用户全程不知道自己在搬空一个会话）。
 * ⇒ 用户看到的现象是「我拖了一下，一张卡不见了」，而产品**什么都没说**。
 *
 * ── 修法 ────────────────────────────────────────────────────────────────
 * 搬空的那一刻必须出声，说清三件事：
 *   ① 哪个会话没了（点名，用户要能对上自己刚拖的那张卡）；
 *   ② 它的最后一条标签**去哪了**（落到哪个会话）；
 *   ③ 这个会话**从列表里消失了**（否则用户会以为它只是被折叠了）。
 *
 * ── 为什么抽成纯函数 ─────────────────────────────────────────────────────
 * 这句话有三种长度（源名/目标名都有、只有源名、都没有），
 * 而 `.tsx` 组件在 node 单测里加载不了 ⇒ 措辞必须能被直接断言。
 */

/**
 * 搬空了一个会话时的提示。
 *
 * @param input.sourceName 被搬空的那个会话的名字（拿不到就传 null）。
 * @param input.targetName 标签落到了哪个会话（拿不到就传 null）。
 */
export const moveEmptiesSessionMessage = (input: {
  sourceName?: string | null;
  targetName?: string | null;
}): string => {
  const source = input.sourceName?.trim();
  const target = input.targetName?.trim();
  const subject = source ? `「${source}」` : '原会话';
  const where = target ? `已移到「${target}」` : '已移走';
  // 「从列表里消失」这半句**必须永远在**：用户真正的疑问是
  // 「那张卡去哪了」—— 只说「标签移走了」会让人以为卡还在。
  return `${subject}的最后一条标签${where}，该会话已从列表移除`;
};
