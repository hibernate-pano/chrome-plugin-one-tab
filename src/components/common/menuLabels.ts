/**
 * ⋯ 菜单里那个登录入口的**逐字**文案。
 *
 * ── 为什么要有这个常量（2026-10-22 审计 P0-2 · 诚实性）─────────────────
 *
 * 2026-10-22 的一轮改动删掉了 ⋯ 菜单里重复的「登录 / 注册」行，只保留状态卡里
 * 内联的「去登录」。删掉是对的 —— 那两处的条件**逐字相同**
 * （`needsLogin` ⟺ 云端后端 && 未登录），一个菜单里两个同义入口会让用户以为
 * 它们不一样。
 *
 * 但删的时候**没有同步三处指向它的文案**：
 *   · 引导第 4 步：OnboardingSteps.tsx
 *   · 同步预览「还没登录」的提示：syncPreviewView.tsx（两处）
 * 三处都还在说「请点右上角菜单『登录 / 注册』」。用户照着去找，在菜单里翻两遍
 * 找不到 —— 入口是存在的，只是叫「去登录」。
 * 这不是「指向不存在的入口」，而是「**承诺了一个不存在的字面量**」，
 * 触犯本产品的诚实性契约（用户按着做却找不到 ⇒ 等于被引导去一个死路）。
 *
 * ⇒ 菜单按钮本身 + 三处文案，统一引用这一个常量。
 * 下次再改这个按钮的文案，四处会一起变，不可能再漂。
 */
export const MENU_LOGIN_LABEL = '去登录';
