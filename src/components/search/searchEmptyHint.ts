/**
 * 搜索结果为空时的那句提示（2026-10-22 审计 L-1）。
 *
 * ── 为什么抽成纯函数 ────────────────────────────────────────────────────
 * 这句话曾经被两处各写一份，且其中一处**无条件承诺**「固定标签」筛选 ——
 * 而那个筛选器在设置里关掉时**根本不渲染**（`collectPinnedTabs` 关闭）。
 * 用户按提示去找一个看不见的筛选项 ⇒ 提示本身成了假线索。
 *
 * 抽成纯函数后：措辞只有一份，node 单测可以直接断言两种开关下的输出，
 * 不必再在源码里 grep 一段**逐字文案**（钉字面量的守卫会把「改对」逼成红灯，
 * 也会把后来的人逼着把文案改回去 —— 见本仓库的「守卫钉死字面量」教训）。
 */

/**
 * @param collectPinnedTabs 设置里「保存时收集固定标签页」是否开着。
 *   关着时**不能**提「固定标签」筛选 —— 那个筛选器压根不存在。
 */
export const searchEmptyHint = (collectPinnedTabs: boolean): string =>
  collectPinnedTabs
    ? '支持搜索会话名称、标签页标题或 URL，也可结合域名、保存时间和固定标签页筛选。如果刚换设备，可先登录后手动同步一次。'
    : '支持搜索会话名称、标签页标题或 URL，也可结合域名和保存时间筛选。如果刚换设备，可先登录后手动同步一次。';
