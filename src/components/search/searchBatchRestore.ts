/**
 * 「批量恢复」（搜索页的「恢复所有匹配标签」）的**判据层**（纯函数）。
 *
 * ── 缺陷本体（2026-10-23 审计 P0-2）────────────────────────────────────────
 * 批量恢复一次做两件事：
 *   ① 把命中的标签页**打开**（新窗口）—— 这一步**含**锁定会话里的；
 *   ② 把命中的标签页**从会话里移除**（= 消费）—— 这一步**不含**锁定会话里的。
 *
 * 修复前的成功提示把两件事混成一句：
 *   「已恢复 N 个标签；命中的标签已从所属会话移除，会话内其余标签保留。」
 * 而执行时锁定会话里的那几条 `continue` 掉了、**根本没被移除**
 * ⇒ 用户以为「命中的那些都从列表里清掉了」，其实那几条还在。
 *
 * ── 为什么根因是「两处各判一遍」 ──────────────────────────────────────────
 * 「哪些会被消费」这个判据在**执行循环**里写了一遍（`if (group.isLocked) continue`），
 * 在**提示文案**里又隐含了一遍（那句「命中的标签已从所属会话移除」）。
 * 两处一旦漂移，就是本缺陷。
 *
 * ⇒ 判据收成**一处**（`planBatchRestore`）：
 *   · 执行循环遍历 `plan.consumable`（真正会被消费的那些）；
 *   · 提示文案用 `plan.keptLocked.length`（真正被留下的那些）。
 *   两边读的是**同一份划分** ⇒ 不可能再漂。
 *
 * ── 为什么抽成纯函数（.ts 而不是留在 .tsx 里） ────────────────────────────
 * 判据层不该依赖 DOM：本仓没有 jsdom，组件没法在 node 里点按钮。
 * 抽出来之后，「提示里说留下的条数 == 真正没被移除的条数」就是一条
 * **可断言的事实**：喂一组带锁定会话的命中，看两个数是不是同一个。
 */
import type { TabGroup } from '@/types/tab';

/** 一条命中（判据只需要知道它属于哪个会话 —— 锁不锁在会话上）。 */
export interface BatchRestoreMatch {
  /**
   * 这条命中所属的会话。
   *
   * 只取 `isLocked`：这是**判据要用到的全部信息**，也是这条不变量
   * 唯一依赖的会话属性。写成 `Pick` 而不是整个 `TabGroup`，是为了让
   * 「这条判据还依赖哪些会话字段」一眼可见。
   */
  group: Pick<TabGroup, 'isLocked'>;
}

/** 批量恢复的划分：**会被消费的** 与 **会被留下的**。 */
export interface BatchRestorePlan<T> {
  /** 真正会被消费（从会话里移除）的那些。 */
  consumable: T[];
  /** 因为会话被锁定而**留在会话里**的那些。 */
  keptLocked: T[];
}

/**
 * 把命中的标签页分成两堆：**会被消费的** 与 **会被留下的**。
 *
 * 判据只有一条：**会话被锁定的不会被消费** ——
 * 锁定承诺「防误删」，而消费（移除记录）不可撤销（无回收站）。
 * 这与逐条打开、批量删除是同一口径。
 *
 * ⚠️ 「打开」不受这条判据约束：锁定会话里的标签页**照样会被打开**
 * （锁定只阻止消费，不阻止打开）—— 这两件事必须分开说，
 * 否则就成了「说打开了几个」与「移除了几个」混成一句的谎报。
 */
export const planBatchRestore = <T extends BatchRestoreMatch>(
  matches: T[]
): BatchRestorePlan<T> => {
  const consumable: T[] = [];
  const keptLocked: T[] = [];
  for (const match of matches) {
    if (match.group.isLocked) keptLocked.push(match);
    else consumable.push(match);
  }
  return { consumable, keptLocked };
};
