/**
 * 「最近使用」排序的说明行文案（v1.33）。
 *
 * ── 为什么这行必须存在，而且只在「最近使用」下出现 ────────────────────────
 *
 * 这一档排序依赖一份**只在本机存在**的记录，而用户看不到这份记录：
 *   · 为什么有些会话排在后面？—— 因为这台设备上没有它的使用记录；
 *   · 换台设备还有吗？—— 没有，这个时间不同步。
 *
 * 不把这两件事在**选中的那一刻**说出来，用户会把它当成「云端也知道的
 * 最近使用」，换设备后顺序变了会以为数据丢了。说明行只在选中这一档时出现
 * （其余档位没有需要额外解释的东西；常驻会在每一屏都占一行）。
 *
 * ── 两份文案的判据 ────────────────────────────────────────────────────────
 *
 * 一份记录都没有时（v1.33 刚上线必然如此）**不能**说「没有记录的排在最后」——
 * 那时**所有**会话都没有记录，用户看到的顺序其实是 `createdAt` 兜底，
 * 说「按使用时间排序」是空的。⇒ 那种情况直接说「还没有使用记录，去打开一个」。
 *
 * ⚠️ 文案逐字取产品定稿，不要改写（守卫 `tests/sessionSortNote.test.ts`
 *   逐字断言）。
 */

/** 有至少一条使用记录时的说明。 */
export const RECENT_USED_NOTE_WITH_RECORDS =
  '按你在这台设备上打开会话的时间排序；没有记录的排在最后。这个时间只记在本机，不同步到其他设备。';

/** 一条使用记录都没有时的说明（v1.33 刚上线必然如此）。 */
export const RECENT_USED_NOTE_WITHOUT_RECORDS =
  '还没有使用记录。打开任意会话后，这里会按最近使用的时间排序。';

/** 说明行的机器可读身份（测试按它定位，不按文案）。 */
export const SESSION_SORT_NOTE_TESTID = 'session-sort-note';

/**
 * @param hasRecords 本机是否已有**至少一条**使用记录
 */
export function recentUsedSortNote(hasRecords: boolean): string {
  return hasRecords ? RECENT_USED_NOTE_WITH_RECORDS : RECENT_USED_NOTE_WITHOUT_RECORDS;
}
