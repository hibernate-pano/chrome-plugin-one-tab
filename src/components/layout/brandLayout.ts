/**
 * 顶栏品牌区的**几何判定口径**（单源）。
 *
 * ── 为什么要有这个模块 ─────────────────────────────────────────────────
 *
 * 2026-10-20 真机实测抓到的缺陷：列表长到需要滚动 ⇒ 出现 8px 滚动条 gutter
 * ⇒ `documentElement.clientWidth` 从 400 降到 392 ⇒ 顶栏品牌列被压窄 ⇒
 * 「TapStack」被 `overflow: hidden` **静默切掉**（用户只看到「TapSta」，
 * 没有任何提示）。这是「声明与行为不符」这一类缺陷里最阴的一种：布局代码
 * 一行没改，只是内容多了一点，文字就被切了。
 *
 * 真机逐档量到的两组数字（同一台机器，唯一变量是列表长度）：
 *
 *   12 个会话（有滚动条）→ clientWidth 392 → 品牌盒 80px → 文字墨迹右边界
 *                          99.8px ≫ 品牌盒右边界 92px ⇒ **被切掉 7.8px**
 *    2 个会话（无滚动条）→ clientWidth 400 → 品牌盒 88px → 墨迹 99.8px = 盒右边界
 *                          ⇒ **刚好放下，一个像素都不剩**
 *
 * 也就是说：**400px 视口下「图标+文字+操作区+内边距」根本放不下**
 * （品牌 87.8 + 栅格间距 8 + 操作区 280 + 左右内边距 24 = 399.8px，
 *  滚动条 gutter 再吃掉 8px 就差 8.2px）。这不是 CSS 写得不好，
 * 是**物理上放不下** —— 必须有一条让位路径。
 *
 * 修法分两层，缺一不可：
 *
 *   ① **降级阈值**（{@link BRAND_ICON_ONLY_MAX_VIEWPORT_WIDTH}）
 *      —— 空间真的不够时，品牌**只留图标**。这是设计意图：品牌是标识，
 *      操作区是功能，该让位的是标识。阈值必须来自**实测**，不是拍脑袋。
 *
 *   ② **运行期兜底**（{@link isBrandContentClipped}）
 *      —— 无论阈值算得准不准、字体缩放多少、平台滚动条多宽，
 *      **品牌名要么完整可见、要么完全消失**，绝不允许「半个字」。
 *      任何只靠阈值兜底的方案都会在某个没测到的宽度上重新变成「TapSta」。
 *
 * ── 阈值是怎么测出来的 ─────────────────────────────────────────────────
 *
 * 真机（Playwright + 真实扩展，12 个会话 ⇒ 必然有滚动条）逐档量：
 *
 *   视口 400px → clientWidth 392 → 品牌盒 79.6px，而「图标+文字」需要
 *                 20(图标) + 8(间距) + 59.8(文字) = 87.8px ⇒ **缺 8.2px**
 *   视口 412px → clientWidth 404 → 品牌盒 89.7px ⇒ 刚好放得下，不裁
 *
 * 阈值取 420px 而不是实测的 409px：滚动条 gutter 的宽度**因平台而异**
 * （macOS 8px / Windows 15–17px），而 CSS 媒体查询只能看到视口宽度。
 * 留出约 11px 余量 ⇒ 即使在 19px 宽的滚动条上，420px 视口也放得下。
 * 代价只是 409–420 这 11px 区间里品牌名提前消失（少几个字，不裁），
 * 换来的是**任何平台都不会再出现半个字**。
 *
 * 与 CSS 的关系：global.css 里的 `@media (max-width: 420px)` 用的就是这个
 * 常量（测试会核对两处一致），CSS 负责「默认就该降级」，运行期兜底负责
 * 「万一还是不够就彻底隐藏」。
 */

/**
 * 低于（含）这个视口宽度时，品牌区只留图标、不显示「TapStack」文字。
 *
 * 依据见文件头：400px 视口（clientWidth 392）放不下「图标+文字」。
 * 留 11px 余量给平台差异更大的滚动条 gutter。
 */
export const BRAND_ICON_ONLY_MAX_VIEWPORT_WIDTH = 420;

/**
 * 品牌名是否被容器裁掉了。
 *
 * 判据用**两条右边界直接比**：`contentRight` 是品牌名自身的右边界，
 * `containerRight` 是品牌盒的右边界。名字比盒子还宽 ⇒ 末尾的「ck」
 * 被 `overflow: hidden` 切掉 ⇒ 用户看到「TapSta」。
 *
 * 为什么不复算「图标多宽 + 文字多宽 + 间距多少」：那样每改一次
 * 字号/字重/语言都要跟着改判据，而且永远追不上真实的布局。
 * 直接量边界，量到什么就是什么。
 *
 * `epsilon` 用来吃掉浮点噪声：实测「刚好放下」的那一档，名字右边界
 * 与盒子右边界同为 99.8/100（亚像素），差值在 0.5px 以内 —— 那不算裁切。
 */
export function isBrandContentClipped(
  contentRight: number,
  containerRight: number,
  epsilon = 0.5
): boolean {
  if (!Number.isFinite(contentRight) || !Number.isFinite(containerRight)) return false;
  return contentRight - containerRight > epsilon;
}
