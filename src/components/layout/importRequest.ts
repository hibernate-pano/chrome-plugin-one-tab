/**
 * 「打开导入」的**跨组件请求总线**（2026-10-22 审计 L-11）。
 *
 * ── 为什么需要它 ────────────────────────────────────────────────────────
 * 导入（OneTab 文本 / JSON 备份）的实现长在 `HeaderDropdown` 里 ——
 * 文件选择、解析、结果提示（成功报数量、失败报原因）都在那儿，
 * 共 200 多行，**不是**能随手复制一份的东西。
 *
 * 而空态（一个会话都没有）需要给「导入数据」一个出口：
 * 新用户从 OneTab 迁过来、或上次导出过 JSON 备份的人，
 * 走到空态时唯一能做的事不该只有「保存当前窗口」。
 *
 * 如果把导入逻辑复制一份到空态，就会出现**两套导入实现** ——
 * 历史事故里最贵的一类（文案与行为漂移）就是这么来的。
 * 所以这里只做一件事：**把「打开导入」这个意图送到真正拥有实现的那一���**。
 *
 * ── 为什么不抄一份文件选择器 ────────────────────────────────────────────
 * 空态自己弹文件选择器、再把文件内容转给 dropdown 的处理函数，
 * 仍然需要跨组件调用 —— 那就是同一件事，只是绕了一圈。
 * 直接开菜单的「导入数据」子菜单，用户还能自己选格式（JSON / OneTab），
 * 行为与从菜单里进来**逐字一致**。
 *
 * ── 单订阅者的理由 ──────────────────────────────────────────────────────
 * 管理页同一时刻只有一个 Header、一个下拉菜单 ⇒ 一个订阅者足够。
 * 若将来出现第二个订阅者，这里要改成多播 —— 现在不做，避免过早泛化。
 */

type ImportRequestHandler = () => void;

let handler: ImportRequestHandler | null = null;

/**
 * 订阅「打开导入」的请求。
 *
 * @returns 取消订阅的函数。
 */
export function onImportRequest(next: ImportRequestHandler): () => void {
  handler = next;
  return () => {
    if (handler === next) handler = null;
  };
}

/**
 * 请求打开导入。
 *
 * @returns 是否有人接单。**没有订阅者时必须让调用方知道** ——
 * 「点了没反应」是本项目明令禁止的失败形态，调用方据此可以给出解释。
 */
export function requestImport(): boolean {
  if (!handler) return false;
  handler();
  return true;
}
