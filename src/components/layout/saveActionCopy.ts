/**
 * 「保存」这个动作的**唯一文案来源**（2026-10-19 审计 I-1 / I-3）。
 *
 * 【为什么必须是单源】保存 = 剪切（关掉当前窗口的标签），这是本产品最贵的
 * 一个动作：不可撤销、且会清空用户眼前的现场。
 *
 * 修复前这句话散落在三处，各写一遍：
 *   · 顶栏按钮可见文字「保存会话」—— **完全不说**会关闭标签
 *   · 顶栏 tooltip / aria-label「保存当前窗口的标签页为会话，并关闭这些标签页」
 *   · 空态按钮「保存当前窗口」+ 一段说清楚了的长描述
 *
 * 结果是：新用户在**真实使用的那条路径**（顶栏按钮）上点下去，窗口里的标签
 * 全没了，而按钮上没有任何可见文字提前说过这件事 —— 「并关闭」只写在
 * hover 300ms 才出现的 tooltip 和读屏 aria-label 里。鼠标快速点击、触屏、
 * 窄屏用户全程看不到。
 *
 * 现在：**可见文字**本身就带「关闭」二字，三处入口共用同一个常量。
 * 「说了什么」与「实际做了什么」不再可能漂移。
 */

/**
 * 保存按钮的可见文案。
 *
 * 短而不含糊：「保存」对用户意味着「存一份副本」，而本产品实际会**关掉**
 * 这些标签。必须在按钮上就说出来 —— 这是唯一无法被忽略的披露位置。
 */
export const saveAndCloseLabel = '保存并关闭';

/** 窄屏（图标形态）下的短文案。仍然带「关」字，不做静默截断。 */
export const saveAndCloseShortLabel = '保存并关标签';

/**
 * 保存动作的完整说明（用于 tooltip / title / 描述）。
 *
 * 一句话讲清三件事：保存什么、关掉什么、能不能撤销。
 */
export const saveAndCloseDescription = '把当前窗口的标签页保存为一个工作会话，并关闭这些标签页（删除不可撤销）';
