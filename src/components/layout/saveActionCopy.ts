/**
 * 「保存」这个动作的**唯一文案来源**（2026-10-19 审计 I-1 / I-3）。
 *
 * 【为什么必须是单源】保存 = 剪切（关掉当前窗口的标签），这是本产品最贵的
 * 一个动作：不可撤销、且会清空用户眼前的现场。
 *
 * 修复前这句话散落在三处，各写一遍：
 *   · 顶栏按钮可见文字「保存会话」—— **完全不说**会关闭标签
 *   · 顶栏 tooltip / aria-label「保存当前窗口的标签页为会话，并关闭这些标签页」
 *   · 空态按钮「保存当前窗口」+ 一段说清楚了的长描述
 *
 * 结果是：新用户在**真实使用的那条路径**（顶栏按钮）上点下去，窗口里的标签
 * 全没了，而按钮上没有任何可见文字提前说过这件事 —— 「并关闭」只写在
 * hover 300ms 才出现的 tooltip 和读屏 aria-label 里。鼠标快速点击、触屏、
 * 窄屏用户全程看不到。
 *
 * 现在：**可见文字**本身就带「关闭」二字，三处入口共用同一个常量。
 * 「说了什么」与「实际做了什么」不再可能漂移。
 */

import type { SavePrecheckKind } from '@/domain/tabGroup/savePrecheck';

/**
 * 保存按钮的可见文案。
 *
 * 短而不含糊：「保存」对用户意味着「存一份副本」，而本产品实际会**关掉**
 * 这些标签。必须在按钮上就说出来 —— 这是唯一无法被忽略的披露位置。
 */
export const saveAndCloseLabel = '保存并关闭';

/**
 * 窄屏（按钮只放得下几个字）下的文案。
 *
 * ── 2026-10-20 几何/语义修复：与长文案**逐字同源** ──────────────────────
 *
 * 原先是「保存并关标签」—— 比长文案「保存并关闭」还多一个字，却少了
 * 「闭」：「关标签」是个半截说法（标签 ≠ 标签页），读起来像「关掉浏览器
 * 标签页」，而产品做的是**把这些标签页收进一个会话**。同一个动作在两个
 * 断点上写着两句话，正是这个文件头想消灭的那种漂移。
 *
 * 为什么不能改成「保存并关标签页」（7 字，最准确）：窄屏按钮里可用宽度
 * 只有 78.4px（实测 6 字 = 78.4px ⇒ 约 13.07px/字），7 字要 91.5px，
 * 放不下 —— 会把顶栏操作区撑宽 13px，反过来又去挤品牌名和搜索框。
 *
 * 所以取**与长文案完全相同**的「保存并关闭」：5 字 ≈ 65px，放得下；
 * 「关」字照样在（关闭的披露没有被截断）；而且从此**只有一个字符串**，
 * 两个断点不可能再漂。
 */
export const saveAndCloseShortLabel = '保存并关闭';

/**
 * 保存动作的完整说明（用于 tooltip / title / 描述）。
 *
 * 一句话讲清三件事：保存什么、关掉什么、能不能撤销。
 */
export const saveAndCloseDescription = '把当前窗口的标签页保存为一个工作会话，并关闭这些标签页（删除不可撤销）';

/**
 * 「这一窗里没有可保存的标签页」的说明（2026-11-06）。
 *
 * ── 为什么这条文案要单独存在 ─────────────────────────────────────────────
 *
 * 空态主 CTA 是新用户第一屏**唯一**的动作。而点扩展图标之后，管理器
 * 就在这一窗里打开 —— 这一窗里除了管理器页本身，往往**一个可保存的标签
 * 都没有** ⇒ 第一次点主 CTA 得到的是「没有可保存的标签页」。
 *
 * 只说「没有」是不够的：用户此刻的问题是「**那我该去哪存？**」
 * （答案是别的窗口 / 先打开几个网页）。这条文案把下一步说出来，
 * 而不是让用户对着一个失败的红字反复点。
 */
export const emptySaveNoTabsText =
  '这个窗口里没有可保存的网页（管理器页本身不算）。切换到有网页的那个窗口再保存，或先打开几个要收起来的网页。';

/**
 * 「这个窗口里能存的全是固定标签页」的说明（2026-11-12）。
 *
 * ── 为什么必须有这一条（不能复用上面那句）──────────────────────────────
 *
 * 上一版预检只有「存得下 0 条」一个判据，失败时一律给 `emptySaveNoTabsText`。
 * 但「存得下 0 条」有**两种**原因，用户要的答案完全不同：
 *
 *   ① 这一窗真的没有可保存的网页（只剩管理器页 / 内部页 / 空窗）
 *      → 解法是「换个窗口 / 先开几个网页」= `emptySaveNoTabsText`
 *   ② 这一窗**有**可保存的网页，但它们**全是固定标签页**，而设置里
 *      「保存时收集固定标签页」是关的（**默认就是关**）
 *      → 解法是「去设置里把那个开关打开」= 这条文案
 *
 * 用错文案的代价是实打实的：照 ① 的提示去开新标签，开完提示照旧（还是 0 个），
 * 用户的观感是「这功能坏了」—— 而真实原因是**一个开关**。
 *
 * ⚠️ 固定标签页在默认设置下**既不保存也不关闭**（它们留在原地），
 *   所以这里说的是「它们没被收进去」，不是「它们丢了」。
 *
 * 设置项的真名是「保存时收集固定标签页」（见 `options/OptionsPage.tsx`）——
 * 这里必须写**一字不差**的那个名字，否则用户按提示去找会找不到。
 */
export const pinnedOnlySaveText =
  '这个窗口里能保存的网页都是固定标签页，默认设置下固定标签页不保存也不关闭。要保存它们，去设置里打开「保存时收集固定标签页」；或者切到有普通网页的窗口再保存。';

/**
 * 一条预检结论对应的文案（完整句 + 短形式）。
 *
 * 短形式是给**按钮**用的（按钮宽度有限，见 `Header.tsx` 的 `sm:inline` /
 * `sm:hidden` 两段），完整句给 `title` / `aria-describedby` / 行内提示位。
 * 两条文案在这里一次成形 ⇒ 顶栏与空态两处**不可能**各写一遍（那必然漂移）。
 */
export interface SavePrecheckCopy {
  /** 完整句：说清「为什么」与「下一步」。 */
  full: string;
  /** 短形式：按钮上放得下的那几个字。 */
  short: string;
}

export const savePrecheckCopy = (kind: SavePrecheckKind): SavePrecheckCopy =>
  kind === 'only-pinned-tabs'
    ? { full: pinnedOnlySaveText, short: '固定标签页未保存' }
    : { full: emptySaveNoTabsText, short: '没有可保存的标签页' };
