/**
 * 「定时拉取」状态行文案（2026-10-22 审计 P1-5）。
 *
 * ── 为什么需要这一行 ────────────────────────────────────────────────────
 *
 * 「同步」其实是**两件**事，而管理页上只看得见其中一件：
 *
 *   · **上传**：每次本地保存 / 重命名 / 删除都会安排一次延迟上传
 *     （syncEngine.scheduleUpload **不检查** syncEnabled）⇒ 一直都在发生；
 *   · **定时拉取**：后台轮询 alarm 只在 `settings.syncEnabled === true`
 *     时注册 ⇒ **默认关闭**。
 *
 * 新用户按引导以为「登录了 = 开了同步」：换到第二台设备登录，会话被拉回 ✓
 * （登录那一下主动拉一次）。但**两台设备都在线时**，第一台存的东西**不会
 * 自动出现在第二台** —— 因为定时拉取默认关。他会得出「这产品同步不可靠」
 * 的结论，而事实上只需在设置里打开开关。
 *
 * 商店文案（CHROMEWEBSTORE.md）早就把这件事说清楚了，管理页上却零处提示
 * ⇒ 引导与管理页必须跟上同一口径。
 *
 * ── 为什么是纯函数 ──────────────────────────────────────────────────────
 *
 * 这段话要同时出现在菜单、引导、可能的设置页；写成纯函数就不会各写一遍
 * 漂移成三个说法（这正是本仓反复修过的同一类问题）。
 */

/** 定时拉取状态行的展示视图。 */
export interface AutoPullStatusView {
  /** 状态行主文案（短，放得进菜单那一行）。 */
  label: string;
  /** 悬停 / 读屏的完整说明（说清「关掉它到底少了什么」）。 */
  title: string;
}

/**
 * 生成「定时拉取」状态行。
 *
 * @param syncEnabled 设置里的自动同步开关（**只管定时拉取**，不管上传）。
 * @param intervalMinutes 轮询间隔（分钟），仅在开启时用得上。
 */
export const autoPullStatusView = (params: {
  syncEnabled: boolean;
  intervalMinutes: number;
}): AutoPullStatusView => {
  if (params.syncEnabled) {
    return {
      label: `定时拉取：已开启（每 ${params.intervalMinutes} 分钟）`,
      title: '后台会按这个间隔从云端拉取更新；本机的改动仍会自动上传。',
    };
  }
  return {
    label: '定时拉取：未开启',
    // 关键是要说清「关掉它少了什么、没少什么」：
    // 用户最容易误解成「关掉 = 不同步了」，而实际上传一直都在发生。
    title:
      '默认关闭：TapStack 不会定时从云端拉取更新（登录时会拉一次，本机的改动仍会自动上传）。' +
      '需要在另一台设备上自动看到更新，请到「设置」里打开自动同步。',
  };
};
