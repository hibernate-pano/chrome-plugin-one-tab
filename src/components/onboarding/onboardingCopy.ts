/**
 * 引导里那段「锁定挡不住什么」的说明（2026-10-23 审计 WC-6）。
 *
 * ── 为什么这两张卡都要有这句话 ────────────────────────────────────────────
 *
 * 锁定的语义是「保护会话**内部**」：不可重命名、不可逐条删标签、
 * 不可把标签拖到别的会话、不参与清理重复。
 * 但它**不保护整个会话本身**：
 *   · 删整个会话仍然可以 —— 只是会先明确提示「该会话已锁定」，
 *     而且这一步**一定**要确认；
 *   · 「删除所有会话」**照样会删掉**锁定会话（确认框会写明其中有几个锁定会话）。
 *
 * 引导里原来一个字没提 ⇒ 用户以为「锁了就删不掉」，
 * 于是该删的没删（垃圾堆里躺着一堆锁定的会话），
 * 或者反过来：以为锁了很安全，结果被「删除所有会话」一次性带走。
 *
 * ── 为什么抽成常量 ────────────────────────────────────────────────────────
 *
 * 锁定卡片与删除卡片说的是**同一件事**，只是各自站在不同的角度。
 * 两处各写一遍中文，迟早会漂成两个说法（这正是本仓反复修过的那类问题）。
 * ⇒ 一个出处、两处引用；守卫从**常量本身**读事实（而不是钉死某段中文）。
 *
 * ── 措辞的来源 ────────────────────────────────────────────────────────────
 *
 * 抄 README.md「锁定防误删」那条与 CHROMEWEBSTORE.md「会话整理」那条的原文，
 * 不另造说法 —— 同一件事在三处（引导 / README / 商店页）必须同一口径。
 */

