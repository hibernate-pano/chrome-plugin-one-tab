/**
 * 「云端服务不可用」的用户可见文案（2026-10-22，402 收口）。
 *
 * ── 为什么单独一个文件（而不是塞进 syncPreviewView 的表）───────────────
 * 这段文案要被**三处**消费：
 *   · 同步失败 toast（SyncButton → resolveSyncFailureCopy）；
 *   · 后台自动同步的一次性通知（backgroundSync）；
 *   · 登录态恢复失败时的那句提示（authSlice / syncEngine）。
 * 三处的**上下文不同**（同步失败 vs 账号不可用），但**同一件事**必须说清：
 * 「你的本地数据没丢、这不是你的操作问题、下一步是什么」。
 *
 * 放在 core/backendUnavailable.ts（判据）与组件之间，让文案本身也是**纯函数**
 * —— 可单测，且三处引用同一份 ⇒ 永远不会漂移成「三个地方三种说法」。
 *
 * ── 这段话必须说清的三件事 ──────────────────────────────────────────────
 *   ① **你的本地数据没有丢** —— 这是用户最怕的（v1.22.0 起无回收站、
 *      删除即物理清除，用户看到同步失败第一反应是「我的会话没了」）；
 *   ② **这不是你的操作问题** —— 服务端项目被限制，用户无论做什么都不对；
 *   ③ **下一步是什么** —— 等我们恢复，或改用自带存储（WebDAV）。
 *
 * ── 为什么**不能**说「请重试」 ──────────────────────────────────────────
 * 项目被封禁时重试一万次结果一样。把用户引向重试 = 让他反复做无用功，
 * 还让他以为「是不是我哪里弄错了」。同理**不能**说「请导出诊断信息」——
 * 诊断信息对用户毫无用处，真正需要知道这件事的是产品负责人。
 *
 * ── 为什么**不能**笼统说「数据没丢」 ────────────────────────────────────
 * 2026-10-22 实测：402 发生在**认输预检的读**与**列探测的读**上
 * （都在 upsert 之前）⇒ **合并上传**路径一个字都没写上云，本地当然完好。
 *
 * 但**覆盖上传**存在一个窄窗口：DELETE 已提交、随后的 upsert 撞 402
 * ⇒ 云端被清空而**本机完好**（不是「部分已写、部分没写」，是「全删了、没写回」）。
 *
 * ⇒ 所以文案**只承诺本地**（本地永远没被写过这句话永远成立），
 * **绝不说「云端的数据也还在」**（覆盖模式下那是假的）。
 *
 * ⚠️ 覆盖模式清空云端**不会造成数据丢失**：云端空了之后，用户本地那份还在，
 * 而「空云端覆盖」被 `decideForceRemoteOverwrite` 拦下（见 SYNC_REASON_COPY 的
 * `overwrite_empty_cloud_refused`），所以下一次覆盖下载不会把本机那份吃掉；
 * 服务恢复后的下一次上传会把云端补成本机的内容。
 */

/** 「本地数据没丢」这句承诺的**统一措辞**（守卫会钉住它的存在）。 */
export const LOCAL_DATA_INTACT = '你的本地会话一个都没有丢';

/**
 * 「这不是你的操作问题」的**统一措辞**。
 *
 * 为什么必须说出来：用户看到「同步失败」的第一反应是「我是不是哪里弄错了」
 * （是不是点了不该点的、是不是删了什么）。服务端项目被限制与他的任何操作
 * 都无关 —— 不说这句，他会反复自我检查、删了重来。
 */
export const NOT_YOUR_FAULT = '这不是你的操作或数据的问题';

/**
 * 「下一步」的**统一措辞**：两件事同时给 —— 等我们恢复 / 改用自带存储。
 *
 * 为什么两个都要给：只说「等我们恢复」，用户就只能干等；只说「改用自带存储」，
 * 他会以为云端永久完了。而两条路都真实存在（设置页有 WebDAV 入口），
 * 只给一条就是把选择权收窄成「等」。
 */
export const NEXT_STEP = '可以等我们恢复，或到设置里改用自带存储（WebDAV）';

/**
 * 「服务端不可用」的用户可见文案（**唯一**出处，三处消费点都引用它）。
 *
 * @param direction 'upload' | 'download' —— 方向只影响「云端」那半句的措辞，
 *   主体（三件事）逐字相同。
 */
export const backendUnavailableCopy = (
  direction: 'upload' | 'download' = 'upload'
): string => {
  const cloudPart =
    direction === 'upload'
      ? '云端暂时不可用，本轮没有上传成功'
      : '云端暂时不可用，本轮没有下载成功';
  // 尾句按方向不同：上传是「补传」，下载是「重新拉取」。
  // 说错方向比不说更糟（下载失败却说「会自动补传」，用户会等一个不会来的上传）。
  const tail = direction === 'upload' ? '恢复后会自动补传。' : '恢复后可以重新下载。';
  return (
    `${cloudPart}：${LOCAL_DATA_INTACT}，${NOT_YOUR_FAULT}。` +
    `${NEXT_STEP}。${tail}`
  );
};

/**
 * 账号态的「服务端不可用」文案（登录态恢复失败时用）。
 *
 * 为什么与同步文案分开：登录失败时用户**还没开始同步**，说「本轮没有上传成功」
 * 会让人困惑（他根本没点同步）。但三件事仍然必须说清 —— 尤其
 * 「你的本地会话一个都没有丢」：登录不上最让人怕的就是「登录不上去 ⇒
 * 我存的东西没了」。
 */
export const backendUnavailableAuthCopy = (): string =>
  `TapStack 云端暂时不可用，现在无法验证你的账号。${LOCAL_DATA_INTACT}，${NOT_YOUR_FAULT}。${NEXT_STEP}。`;

/**
 * 后台自动同步的一次性通知文案（2026-10-22）。
 *
 * 为什么通知里也要说「本地没丢」：后台同步失败时**用户什么都没点**，
 * 界面上什么动静都没有 —— 唯一的触达通道就是这条通知。它必须自带
 * 「不需要你做什么、你的数据没事」这两层信息，否则用户要么焦虑、
 * 要么反复开扩展试。
 */
export const backendUnavailableBackgroundNotice = (): string =>
  `后台自动同步已暂停：${LOCAL_DATA_INTACT}，${NOT_YOUR_FAULT}。${NEXT_STEP}。恢复后会自动继续。`;

/**
 * 「核不到登录态」（断网 / 超时 / 通道断了）的用户可见文案（2026-10-23 第 50 轮）。
 *
 * ── 为什么必须有这一档，而且**不许**复用「未登录」那一句 ────────────────
 * 「核不到」与「核到没登录」在**事实**上完全不同：
 *   · 核到没登录 ⇒ 用户需要**重新登录**（下一步是输密码）；
 *   · 核不到     ⇒ 用户**可能登录着**，只是我们暂时确认不了
 *     （下一步是**检查网络**，不是输密码）。
 * 合成一句 ⇒ 断网时用户去重新输密码，而重新登录在断网时**必然失败** ⇒ 死循环。
 *
 * ⚠️ 因此这一句里**不许出现「请重新登录 / 登录已过期 / 未登录」** ——
 * 守卫会钉住这条性质（见 tests/guards/authVerdictHonesty.test.ts）。
 *
 * 与「服务端不可用」那句的差别：那句是「**我们的**云端出问题了，等我们恢复」，
 * 这一句是「**你的网络**暂时不通」，下一步是用户自己能做的「检查网络」。
 */
export const authUnknownCopy = (): string =>
  `现在联系不上 TapStack 云端，暂时无法确认登录状态。${LOCAL_DATA_INTACT}。请检查网络后重试。`;
