/**
 * 「云端有会话这轮读不出来」的用户可见文案（2026-10-20）。
 *
 * ── 为什么必须有这个模块 ──────────────────────────────────────────────────
 *
 * 云端下行时，某些会话**整组读不出来**会被跳过：
 *   · 内容形状读不出来（解密/解析失败）—— src/utils/supabase/download.ts
 *   · 还原率不达标（URL 没通过安全校验）
 *   · tabs 表被网关截断（db-max-rows 静默截断）
 *   · 单组处理异常
 *
 * 这件事过去**只写进日志**（download.ts 的 logError），界面报的是「同步成功」。
 * 于是界面在**说谎**：用户看到列表里少了几组，却无法解释自己为什么少了东西 ——
 * 而 v1.22.0 起删除即物理清除、无回收站，用户的第一反应必然是
 * 「是不是同步把我的东西弄丢了」。
 *
 * 本仓库的纪律是「声明 = 行为」：文案/README 承诺的必须正好是代码做到的事；
 * **反过来**，代码做到的重要事实也不能藏起来只写日志。这个模块就是那个
 * 「藏起来的事实」的出口。
 *
 * ── 为什么必须分「合并 / 覆盖」两种模式 ──────────────────────────────────
 *
 * 两种模式下的**事实不同**，用一句文案覆盖两种模式 ⇒ 至少有一种在说假话：
 *
 *   · 合并（forceRemote=false）：被跳过的那几份，本机那份**一直都在**
 *     （合并模式下它们本来就保留），这轮只是没从云端拿到新的；
 *   · 覆盖（forceRemote=true）：本机那几份**被特意保住了**
 *     （云端那份根本没拿到 ⇒「云端说了算」这条规则不适用），
 *     其余本地会话已按云端覆盖。
 *
 * ⚠️ **依赖**：覆盖模式那句「已保留你本机的那几份」依赖引擎层的同一批修复
 * （云端读不出来的那组，在覆盖模式下保留本机那份；见
 * src/services/syncEngine.ts 的 MergeResult.skippedRemoteGroups）。
 * 两条必须**一起落地** —— 引擎侧没落地而只有这段文案，就是一句谎话。
 * 合并模式那句不依赖引擎修复（合并语义下本机那份本来就保留）。
 *
 * ── 为什么不是「同步失败」 ────────────────────────────────────────────────
 *
 * 这一轮**没有硬失败**，重试也不会变好（云端那行还是读不出来）。
 * 说成失败 ⇒ 界面弹「下载失败，请重试」⇒ 用户一直点重试，那是**误导性失败**，
 * 比谎报成功更糟。所以：
 *   · 级别固定为「信息级」（severity: 'info'），不是 error；
 *   · 文案里不出现「失败 / 请重试」这类会把用户导向无意义重试的词。
 *
 * ── 文案必须说清的四件事（产品负责人定的硬要求）─────────────────────────
 *
 *   ① 几组没读回来（数字必须出现在文案里）；
 *   ② 云端那一份还在（没被删、没被覆盖）—— 用户最怕「云端的东西被我同步弄丢了」；
 *   ③ 本机未受影响（合并：已有会话没被动过；覆盖：那几份被保住了）；
 *   ④ 下一步（用户能做什么），而不是只报告事实。
 *
 * 本模块是**纯函数**（不碰 DOM、不碰 chrome.*），因此可以直接单测 ——
 * 这也是仓库既有的做法（syncPreviewView / saveActionCopy / importResultCopy）。
 */

export type SyncDirection = 'upload' | 'download';

/** 下载的两种模式（覆盖 / 合并）。两种模式的事实不同，文案也不同。 */
export type SkippedRemoteGroupsMode = 'overwrite' | 'merge';

export interface SkippedRemoteGroupsInput {
  /** 本次同步的方向。只有下载方向才可能「云端有会话读不出来」。 */
  direction: SyncDirection;
  /** 下载模式：覆盖 / 合并。 */
  mode: SkippedRemoteGroupsMode;
  /**
   * 本轮云端读不出来、被整组跳过的会话数。
   *
   * 字段缺失（老后端 / 测试替身 / 这轮没跳过任何会话）⇒ 0 ⇒ **一个字都不多说**。
   */
  count?: number | null;
}

export interface SkippedRemoteGroupsNotice {
  /** 完整文案。 */
  text: string;
  /**
   * 提示级别。固定为 'info' —— 这一轮没有硬失败（见文件头）。
   *
   * 级别放在这里而不是让组件自己选，是因为「不许说成失败」是一条**产品决定**：
   * 组件里随手写个 'error' 就是把这条决定悄悄改掉了，而它比任何一条文案断言
   * 都更容易被改坏。
   */
  severity: 'info';
  /** 展示时长（毫秒）。文案较长，给足阅读时间。 */
  durationMs: number;
}

/** 信息级提示的展示时长。 */
const NOTICE_DURATION_MS = 6000;

/**
 * 把「引擎报上来的数字」变成一个可用的计数。
 *
 * 字段可能缺失（老后端 / 测试替身），也可能是脏值。**任何拿不准的情况都当作
 * 0**（= 没有会话被跳过 ⇒ 什么都不说），而不是当作「有会话被跳过」。
 */
const toSkippedCount = (raw: number | null | undefined): number => {
  if (typeof raw !== 'number' || !Number.isFinite(raw)) return 0;
  return Math.floor(raw);
};

/** 下一步的落点：「⋯」菜单里的「问题反馈」（真实存在的菜单行）。 */
const NEXT_STEP = '请在「⋯」菜单的「问题反馈」里说明情况';

/**
 * 合并模式的文案。
 *
 * 事实：被跳过的那几份，本机那份一直都在（合并模式下它们本来就保留）；
 * 云端那几行原封未动；本机已有的会话没有因为「跳过」而被改动。
 *
 * ⚠️ 为什么说「你本机**已有的**会话」而不是「你本机**对应的**记录」：
 * 读不出来的会话**可能只存在于云端**（比如另一台设备写的、设备绑定密钥
 * 解不开）—— 那种情况下本机压根没有对应记录，说「你本机对应的记录原样保留」
 * 就是一句不存在的保证。「已有的会话没被改动」在两种情况下都成立。
 */
const mergeCopy = (count: number): string =>
  `云端有 ${count} 个会话读取不出来，这轮没有下载到本机。` +
  '它们在云端的那份原样保留，没有被删除或覆盖；' +
  '你本机已有的会话也没有因为读不到云端那份而被改动。' +
  `要处理它们，${NEXT_STEP}。`;

/**
 * 覆盖模式的文案。
 *
 * 事实：云端那几行读不出来 ⇒「云端说了算」不适用 ⇒ 这几份**没有参与这次覆盖**
 * （本机有副本的那几份被保住；本机压根没有副本的那几份，云端那一份原样留着）；
 * 其余本地会话已按云端覆盖；云端那几行原封未动。
 *
 * ⚠️ 2026-10-20 P1：原文案第一句是「已保留你本机**对应的**会话」——
 * 那是一句**不存在的保证**：读不出来的会话**可能只存在于云端**（另一台设备
 * 写的、本机用设备绑定密钥解不开），那种情况下本机压根没有对应记录，
 * 说「已保留你本机对应的会话」= 承诺了一件没发生的事。
 * 合并模式早就避开了这个坑（「你本机**已有的**会话」），覆盖模式当时没跟上。
 * 现在两句都只承诺**可判定的**事实：
 *   · 「没有用云端内容覆盖它们」—— 覆盖下载确实没把这几份换掉；
 *   · 「你本机已有的那几份被保住了」—— 本机**有**副本的那几份一定被保住。
 */
const overwriteCopy = (count: number): string =>
  `云端有 ${count} 个会话读取不出来，没有用云端内容覆盖它们；` +
  '你本机已有的那几份被保住了，其余本地会话已按云端内容覆盖。' +
  '这几个会话在云端的那份原样保留，没有被删除或覆盖。' +
  `要处理它们，${NEXT_STEP}。`;

/**
 * 「云端有会话读不出来」这条提示 —— 没有这回事就返回 null（**一个字都不多说**）。
 *
 * 返回 null 的三种情况（都必须静默）：
 *   · 字段缺失 / 不是数字（老后端、测试替身）；
 *   · count === 0（这轮没跳过任何会话 ⇒ 弹「0 个会话读不出来」是纯噪音）；
 *   · 方向是上传（这个事实只可能出现在下载方向）。
 */
export const skippedRemoteGroupsNotice = (
  input: SkippedRemoteGroupsInput
): SkippedRemoteGroupsNotice | null => {
  if (input.direction !== 'download') return null;

  const count = toSkippedCount(input.count);
  if (count <= 0) return null;

  return {
    text: input.mode === 'overwrite' ? overwriteCopy(count) : mergeCopy(count),
    severity: 'info',
    durationMs: NOTICE_DURATION_MS,
  };
};
