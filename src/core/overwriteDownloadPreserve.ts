/**
 * 覆盖下载（forceRemote）时，**本机**哪些会话会被保住（2026-10-23，第 51 轮）。
 *
 * ── 背景 ────────────────────────────────────────────────────────────────
 * 云端有些会话**这台设备读不出来**（形状不可恢复 / 还原率不达标 / tabs 表被
 * 网关截断 / 单组处理异常 —— 见 utils/supabase/download.ts 的跳过清单）。
 * 它们的**云端行仍在**（一个字节都没被动过），只是这一轮没能还原出来。
 *
 * 覆盖下载的语义是「本地以云端为准」—— 但那句话有个前提：**我们确实拿到了
 * 云端那一份**。对读不出来的那几组，我们对云端的态度**一无所知**，
 * 于是绝不能把「没读到」翻译成「云端没有」⇒ **本机那一份必须活下来**
 * （D-6，2026-10-20）。
 *
 * ── 为什么判据抽成纯函数（而不是留在引擎里）──────────────────────────────
 *
 * 仓库的范式是「判据抽纯函数、IO 留在 IO 层」：同一个判据要**同时**被
 *   · 执行侧（services/syncEngine.ts 的覆盖下载：算「哪些本机会话进合并结果」）
 *   · 预览侧（utils/syncPreview.ts 的下载预览：算「覆盖后本地还剩什么」）
 * 用到。这两处若各写一份，其中一份改了另一份没改 ⇒ **预览会预告一个与实际
 * 结果相反的结果**（把「不会发生的事」说成会发生）—— 那正是本仓库反复出现
 * 的事故类型（见 docs/RELEASE-NOTES.md「预览必须与实际同源」那条纪律）。
 *
 * ⚠️ 2026-10-23 修的就是这个：下载预览原先**没有**这份事实（它只拿到
 * 「读到的」），于是把「云端读不出来、本机有副本」的那几份算成了
 * 「覆盖后会被删除」—— 而执行侧明明会保住它们。
 */

/** 判据需要的最小形状（本仓的会话形状满足它；测试替身也满足）。 */
export interface PreserveableGroup {
  id: string;
  isDeleted?: boolean;
}

/**
 * 覆盖下载时**被保住**的本机会话（云端这轮读不出来、本机有副本的那些）。
 *
 * 判据只有一条：**活跃** ∧ **在跳过清单里**。
 *
 * 为什么墓碑不算：墓碑是「本机盖的删除标记」—— 删除意图有**本机证据**，
 * 与云端读不读得出来无关（见 syncEngine 里 legacyLocalTombstoneIds 那段）。
 * 把墓碑也保住 = 把「用户已经删掉的会话」又留在本机。
 *
 * 纯函数：同样的两份事实 ⇒ 同样的结果（无 IO、无随机、无时钟）。
 */
export function preservedLocalGroups<T extends PreserveableGroup>(
  localGroups: readonly T[],
  skippedIds: ReadonlySet<string>,
): T[] {
  return localGroups.filter(group => !group.isDeleted && skippedIds.has(group.id));
}
