/**
 * 导入的体积上限（纯函数 + 文案；无 IO）。
 *
 * ── 这道上限守的是什么 ────────────────────────────────────────────────────
 *
 * 导入是**唯一**一条「整份文件进内存」的路径：文件文本 → JSON.parse →
 * 归一化 → 跨进程消息。而**分块**（见 importChunking）只解决了「消息体太大」，
 * 解决不了「弹窗被撑爆」：
 *
 *   · 64MB 的 JSON 文本 ⇒ 解析出的对象图约为文本的 2~3 倍 ⇒ 弹窗进程吃掉
 *     200MB+ 堆；再大就直接被 Chrome 杀掉 ⇒ 用户看到的是「导入失败」，
 *     而**文件其实没坏** —— 一句误导的解释。
 *
 * ⇒ 上限必须存在，但**必须说清为什么、怎么办**。
 *
 * ── 数字怎么来的 ──────────────────────────────────────────────────────────
 *
 * 64MB：
 *   · 解析后的堆占用 ≈ 150~200MB —— Chrome 扩展弹窗扛得住；
 *   · 约等于 1.5~2 万个会话的备份 —— 远超绝大多数用户；
 *   · 分块后单条消息远小于 Chromium 的消息上限 ⇒ 「发不出去」不再是失败原因。
 *
 * ⚠️ 这条上限**不是「会话数量上限」**：本机可以存多少个会话是另一回事
 * （IndexedDB 配额），仓库不设会话数上限。本上限只约束**一次导入的文件大小**。
 */

/** 一次导入的文件大小上限（字节）。 */
export const MAX_IMPORT_FILE_BYTES = 64 * 1024 * 1024;

/** 字节数 → 「xx MB」（一位小数；小于 1MB 时按 KB 说）。 */
export function formatFileSize(bytes: number): string {
  if (!Number.isFinite(bytes) || bytes < 0) return '未知大小';
  const mb = bytes / (1024 * 1024);
  if (mb >= 1) return `${mb.toFixed(1)} MB`;
  return `${Math.max(1, Math.round(bytes / 1024))} KB`;
}

/**
 * 文件太大时的完整说明。
 *
 * 【为什么必须给出路】只说「太大了」而不说怎么办，用户就只能看着自己的备份
 * 干瞪眼。而**确实有出路的**：本扩展同时支持 OneTab 文本格式，
 * 那份文件小得多（只有网址），可以在原设备上分批导入。
 */
export const importFileTooLargeMessage = (bytes: number): string =>
  `这个备份文件太大了（${formatFileSize(bytes)}，一次导入的上限是 ${formatFileSize(
    MAX_IMPORT_FILE_BYTES
  )}）——` +
  `文件本身没问题，是本机一次读不下这么大的文件。` +
  `请在原设备上改用「导出为 OneTab 格式」（文件小得多），再分批导入。`;
