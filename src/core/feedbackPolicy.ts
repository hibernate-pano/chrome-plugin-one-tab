/**
 * 「该不该出声」的判据层（2026-10-25「安静的成功」）。
 *
 * ── 一句话 ────────────────────────────────────────────────────────────────
 * **界面状态 = stdout，提示 = stderr。成功是状态，不是事件。**
 *
 * ── 这条判据解决什么问题 ────────────────────────────────────────────────
 * 以前「说不说成功」散在 119 处调用点里，每个点自己拍脑袋 ⇒ 界面**已经自明**
 * 的结果被重复念了一遍（窗口开了、卡片还在、图标翻了，用户看得见却又被告知）。
 * 播报一旦多到盖住结果，它就从「信息」变成「噪声」，用户要自己分辨哪条有用。
 *
 * 于是判据收成一句话：**结果能不能从界面状态自己看出来？能 ⇒ 沉默；不能 ⇒ 说事实。**
 *
 * ── 判据层只管「该不该出声」，不管「在哪说」 ────────────────────────────
 * 载体是 toast 还是常驻位置（菜单行 / 卡片行 / 设置项 hint）由调用方决定；
 * 判据层不含任何文案 —— `FeedbackDecision` 连 `message` 字段都没有：
 * 事实那句话本来就在调用方手里（它得先知道自己要说什么才谈得上说），
 * 判据只回答「该不该出声」。⇒ 判据层可以无浏览器直测（node:test），
 * 也不会因为文案改版而连累判据。
 *
 * ── 为什么是三档而不是「说 / 不说」 ──────────────────────────────────────
 * `silent`（沉默）/ `fact`（说一件界面表达不了的事实）/ `error`（失败、部分失败、
 * 结果对不上）。只分两档的话，「说事实」和「报失败」会挤在同一档，
 * 而这两者的**严重程度与时长策略完全不同**（失败要常驻，事实三秒即可）。
 *
 * ── 为什么「不可逆」要单独成为一条 ──────────────────────────────────────
 * 一次**不可逆**（消费 / 删除 / 清空）且界面又表达不了结果的操作，
 * 如果还**没有退路**（没有撤销按钮），用户就既看不到结果、也无法反悔
 * ⇒ 这是最坏情况，绝不许静默。宁可吵一次，也不要让人以为什么都没发生。
 *
 * ⚠️ 这条判据取 **fail-closed**：`hasEscape` 没写 = **没有退路**，
 * 不 = 「不知道有没有」。理由同上 —— 不可逆操作拿不到撤销入口时，
 * 宁可多喊一句，也不要让用户在一件无法反悔的事上毫无提示。
 */
export type FeedbackLevel = 'silent' | 'fact' | 'error';

/** 一件事的结果，界面能不能自己说出来。 */
export type ResultVisibility = 'self-evident' | 'hidden';

export interface FeedbackInput {
  /** 结果是否完全能从界面状态看出来。 */
  visibility: ResultVisibility;
  /** 界面看不见、但用户必须知道的事实（**文案由调用方保留**，判据只看有没有）。 */
  hiddenFact?: string;
  /** 这次操作不可逆（消费 / 删除 / 清空）。 */
  irreversible?: boolean;
  /** 有没有退路（撤销按钮）。 */
  hasEscape?: boolean;
}

export interface FeedbackDecision {
  level: FeedbackLevel;
  /** 判据给出的理由（供守卫与调试，不进界面）。 */
  reason: string;
}

/**
 * 判据本体：纯函数、零依赖、无浏览器直测。
 *
 * 规则**按顺序短路**，每一条命中都会在 `reason` 里说明命中的是哪一条
 * （守卫与调试要能看出「为什么判成了这一档」）。
 */
export const decideFeedback = (input: FeedbackInput): FeedbackDecision => {
  const { visibility, hiddenFact, irreversible, hasEscape } = input;

  // ① 不可逆 + 界面表达不了 + 没有退路 ⇒ 最坏情况，不许静默。
  //
  // 为什么排在最前：它是**唯一**一条能升级成 error 的规则 —— 而 error 比 fact 重
  // （失败要常驻，事实三秒即可）。用户既看不到结果、又无法反悔时，
  // 沉默就是欺骗，这时「有一件事实要说」不足以替代它。
  // ⚠️ `hasEscape !== true` 是 fail-closed：没写 `hasEscape` 一律当「没有退路」。
  if (visibility === 'hidden' && irreversible === true && hasEscape !== true) {
    return {
      level: 'error',
      reason:
        '命中规则①：不可逆 + 界面表达不了 + 没有退路 —— 用户看不到结果也无法反悔 ⇒ ' +
        '升级成错误，不许静默。',
    };
  }

  // ② 有一件界面看不见的事必须说。
  //
  // 为什么排在「界面自明」之前：结果自明**不等于**没有盲区 ——
  // 「清掉了 3 个重复标签」这件事界面永远表达不了（列表只是变短了）。
  // 空白串不算「有一件事」（没有事实就没有话可说）。
  if (typeof hiddenFact === 'string' && hiddenFact.trim().length > 0) {
    return {
      level: 'fact',
      reason: '命中规则②：有一件界面看不见、但用户必须知道的事实 ⇒ 说事实（判据只判有没有，不碰文案）。',
    };
  }

  // ③ 结果本身界面表达不了（分不清「打开了」还是「被删了」）⇒ 说事实。
  //
  // 为什么是 fact 而不是 error：界面表达不了 ≠ 出错了。
  // 「用户看不到结果」只是需要补一句说明；只有**失败**才是 error。
  if (visibility === 'hidden') {
    return {
      level: 'fact',
      reason: '命中规则③：结果界面表达不了（分不清「打开了」还是「被删了」）⇒ 说事实。',
    };
  }

  // ④ 其余 ⇒ 沉默。界面自己就是回执。
  return {
    level: 'silent',
    reason: '命中规则④：结果完全在界面自明 ⇒ 沉默（成功是状态，不是事件）。',
  };
};
