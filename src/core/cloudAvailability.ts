/**
 * 「云端在不在服务」的**判据层**（纯函数，2026-10-23，第 51 轮）。
 *
 * ── 为什么判据要单独抽出来 ────────────────────────────────────────────────
 * 「状态码 ⇒ 云端在不在服务」是一条**判据**，不是 IO：
 * 它决定界面说「等我们恢复」还是「检查你的网络」，而它在 IO 层里被
 * `fetch` 的细节包着 ⇒ **测不到**（改了它，测试照样绿）。
 *
 * ⇒ 判据抽成纯函数，IO 只负责把状态码喂进来（见 utils/supabase/cloudAvailability.ts）。
 *
 * ── 判据的依据是**状态码**，不是文案 ──────────────────────────────────────
 * 与本仓既有纪律一致（见 core/backendUnavailable.ts）：文案随时会被改写，
 * 而「服务端现在不服务」这件事在服务端有稳定的机器标记（402/503/52x）。
 */
import { UNAVAILABLE_STATUS_CODES } from './backendUnavailable';

/**
 * 云端的三种状态。
 *
 * ⚠️ 「不知道」（unknown）与「不可用」（unavailable）**必须分开**：
 * 前者说「等网络」，后者说「等我们恢复」—— 指错了下一步就是骗用户。
 */
export type CloudAvailability =
  /** 云端在服务。 */
  | 'available'
  /** 云端明确不服务（402/503/52x，或「我们的 key 被拒」）⇒ 等我们恢复。 */
  | 'unavailable'
  /** 问不到（断网/超时/被拦）⇒ **不知道**。 */
  | 'unknown';

/**
 * 「我们的 apikey 被拒」的状态码（**探活口径**）。
 *
 * ⚠️ 这条判据**只**适用于探活（`/auth/v1/health`）—— 因为**探活带了 apikey、
 * 且不带用户会话**。生产实测（2026-10-23，对着线上项目打的）：
 *
 *   · 不带 apikey  ⇒ **401** `{"message":"No API key found in request"}`
 *   · 带一个错的 apikey ⇒ **401** `{"message":"Invalid API key"}`
 *   · 带**对的** apikey + 项目健康 ⇒ 200
 *
 * ⇒ 探活拿到 401/403 时，它**不可能**是「用户没登录」（我们根本没带用户令牌）
 * ⇒ 它只能是「**网关拒了我们的 key**」（key 被轮换 / 项目被暂停 / key 配错）。
 *
 * ⚠️ 为什么这必须 fail-closed（判「不可用」而不是「在服务」）：
 * key 被拒之后，**每一个**请求都会以同样的方式失败 ⇒ SDK 的刷新请求也会拿到
 * 401 ⇒ auth-js 把 401 当成「服务端明确拒绝」⇒ `_removeSession()`
 * ⇒ **用户的会话被删掉**（一次配置/网关故障 = 一次全员登出）。
 * 放行的代价（会话被删，且用户再也登不进去）远大于拦下的代价
 * （用户看到「云端暂时不可用，稍后重试」，会话还在，恢复后自动继续）。
 */
export const PROBE_KEY_REJECTED_STATUSES: readonly number[] = [401, 403];

/**
 * 状态码 ⇒ 云端在不在服务（**纯函数**，**探活口径**）。
 *
 * ⚠️ 关键取舍：只有两类应答判「不可用」——
 *   ① **服务端明确不服务**：402/503/52x（`UNAVAILABLE_STATUS_CODES`）；
 *   ② **我们的 key 被拒**：401/403（见 `PROBE_KEY_REJECTED_STATUSES` 的论证）。
 * 其余任何应答都判「在服务」（含 404/429 —— 那说明**它答了**，只是这一句不是
 * 我们要的）。
 *
 * 为什么不能反过来（「只有 2xx 才算在服务」）：404（版本路径变了）是**答了**，
 * 判成「不可用」就是把用户的网络说成「我们挂了」，指错了下一步。
 *
 * ⚠️ 401/403 这一档**是探活专有的**：同一个 401，在**带用户令牌**的请求上
 * 意味着「用户的会话过期了」（那是**用户侧**的问题，不该说成「等我们恢复」）。
 * 区别只在于「**探活带了什么**」⇒ 所以这条判据住在**探活**这一层，
 * 不许被搬到别的地方去用。
 */
export const classifyAvailabilityStatus = (
  status: number,
): 'available' | 'unavailable' =>
  UNAVAILABLE_STATUS_CODES.includes(status) || PROBE_KEY_REJECTED_STATUSES.includes(status)
    ? 'unavailable'
    : 'available';
