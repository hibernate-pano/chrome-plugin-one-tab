/**
 * 导入失败的**原因说明**（纯函数；无 IO）。
 *
 * 【为什么要单独抽出来】
 *
 * 导入失败有好几种**性质完全不同**的原因，而它们对用户要做的事也完全不同：
 *
 *   · 文件读不懂 → 用户该**换文件**（或去修文件）；
 *   · 写盘失败   → 用户该**腾空间 / 检查权限 / 稍后重试**；
 *   · 内容全不可导入 → 用户该**回文件里核对**。
 *
 * 修复前三种共用一句「导入未能完成……可能是浏览器存储空间不足或扩展无写入权限」
 * —— 而实测复现的真实故障是「文件里一个组的时间戳越界 ⇒ 归一化抛异常」，
 * 用户看到「存储空间不足」⇒ 去清存储（没用）而不是去修文件（有用）。
 * ⇒ **解释必须与故障对得上号**，否则用户被引导去做无用功。
 *
 * 抽成纯函数是为了**能直接断言文案本身**（守卫不必去猜源码里哪段 catch
 * 对应哪条理由 —— 那种断言改个位置就红，且不红的时候也不代表诚实）。
 */

/** 文件读不懂（结构不是本扩展的 JSON 备份格式）。 */
export const importFileUnreadableReason = (sourceCount: number): string =>
  sourceCount === 0
    ? '这个文件里没有可导入的会话：请确认选中的是本扩展导出的 JSON 备份文件'
    : `这个文件读不懂（文件内共 ${sourceCount} 个会话，但结构不是本扩展导出的 JSON 备份格式）。` +
      `请确认选中的文件没被改过、也没被别的工具截断。`;

/** 写盘失败（读文件这关已经过了 ⇒ 责任在存储侧，不在文件）。 */
export const importWriteFailedReason = (sourceCount: number): string =>
  `导入未能完成（文件内共 ${sourceCount} 个会话，本次一个都没落盘）。` +
  `这是写入本机存储时失败：可能是浏览器存储空间不足或扩展无写入权限；` +
  `请稍后重试，若反复失败请到「问题反馈」里说明。`;

/** 文件读得懂，但里面没有可导入的网址。 */
export const importNoImportableGroupReason = (
  sourceCount: number,
  failedGroups = 0
): string => {
  const failedNote =
    failedGroups > 0 ? `另有 ${failedGroups} 个会话的数据读不出来，已跳过。` : '';
  return (
    `文件内共 ${sourceCount} 个会话，但没有任何可导入的网址：` +
    '全部为空会话，或只含无法保存的网址（javascript:、data: 等危险协议，' +
    `以及 chrome://、edge:// 等浏览器内部地址会被跳过）。${failedNote}`
  );
};
