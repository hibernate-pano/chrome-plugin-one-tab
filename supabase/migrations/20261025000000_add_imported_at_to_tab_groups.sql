-- 迁移 20261025：add_imported_at_to_tab_groups
-- 说明：来源格式**不带时间戳**的导入件（目前只有 OneTab —— 社区标准就是
-- `URL | 标题` + 空行分组）**没有保存时间**。导入时只能把 `created_at` 写成
-- 「现在」⇒ 界面就在说假话：卡片写着「今天」、列表最上面塞满几年前的旧记录、
-- 「保存时间 = 24 小时内」把它们全算进去。
--
-- 本列承载「这个会话的**保存时间未知**」这个事实：
--   · 有值 ⇒ 该会话的保存时间未知（显示成「导入 · …」、不参与按保存时间的筛选、
--     在「最近保存」排序里排在已知保存时间的会话之后）；
--   · 无值 ⇒ `created_at` 就是它真正的保存时间。
--
-- 客户端侧已有 42703 降级（`supportsImportedAt()` 探测不到列就整列省略，
-- 见 `src/utils/supabase/probe.ts`）⇒ 本迁移执行前后都不阻塞同步 ——
-- 先发版后执行迁移是安全的；迁移没跑之前，**云端不承载**这个标记
-- （换设备下载回来那条会话会显示成普通会话 —— 这是已知边界，不是丢数据）。
--
-- `timestamptz NULL`：值 = 该会话**进到本机的时间**（对 OneTab 导入就是导入那一刻）。
-- 不用 `not null` ⇒ 存量行天然是 NULL（它们的保存时间是已知的）。

alter table public.tab_groups
  add column if not exists imported_at timestamptz null;
